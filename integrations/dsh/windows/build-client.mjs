import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
import {remoteContract} from './src/contract.js';
const commonBuild=new URL('../../common/windows/build.mjs',import.meta.url);
if(existsSync(commonBuild)){
  const {stageUpdaterCommon}=await import(commonBuild.href);
  await stageUpdaterCommon(new URL('./',import.meta.url));
}else await import('./updater/common/index.js');
const require=createRequire(import.meta.url),{feedbackUrl}=require('./client/feedback.cjs');
const version=JSON.parse(readFileSync(new URL('./package.json',import.meta.url),'utf8')).version;
const source=readFileSync(new URL('./client/page.cjs',import.meta.url),'utf8');
const model=readFileSync(new URL('./client/state.cjs',import.meta.url),'utf8');
const feedback=readFileSync(new URL('./client/feedback.cjs',import.meta.url),'utf8');
const logo='data:image/png;base64,'+readFileSync(new URL('./assets/finshield.png',import.meta.url)).toString('base64');
const artifact=`// Generated by build-client.mjs. Edit client/page.cjs.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(remoteContract.package)},factory:(require)=>{\nconst module={exports:{}}; const exports=module.exports;\nconst REMOTE_CONTRACT=${JSON.stringify(remoteContract)};\nconst BRAND_LOGO=${JSON.stringify(logo)};\nconst FEEDBACK_MODEL=(()=>{const module={exports:{}};${feedback}\nreturn module.exports;})();\nconst PROTECTION_MODEL=(()=>{const module={exports:{}};${model}\nreturn module.exports;})();\n${source}\nreturn module.exports;\n}});\n`;
writeFileSync(new URL('./client.js',import.meta.url),artifact);

// Before installation, Discover can include only the published page's version.
for(const language of ['zh','en']) {
  const document=new URL(`./detail/${language}.md`,import.meta.url);
  const text=readFileSync(document,'utf8');
  const label=language==='zh'?'反馈问题 ↗':'Report a problem ↗';
  const link=`[${label}](${feedbackUrl({version,source:'discover',language})})`;
  const existing=/\[(?:反馈问题 ↗|Report a problem ↗)\]\(https:\/\/github\.com\/finogeeks\/finsafe\/issues\/new\?[^)]*\)/;
  const product=language==='zh'?'[认识FinShield ↗](https://finaios.ai/zh-hans/products/finshield/)':'[Meet FinShield ↗](https://finaios.ai/zh-hans/products/finshield/)';
  const updated=existing.test(text)?text.replace(existing,link):text.replace(product,product+'　'+link);
  if(!updated.includes(link))throw Error('Missing Discover footer: '+language);
  writeFileSync(document,updated);
  const draft=new URL(`../../../windows/prototypes/assets/finshield-discover.${language}.md`,import.meta.url);
  if(existsSync(draft))writeFileSync(draft,updated);
}
